export function createDefaultPreferencesForRole(role: UserRole): UserPreferenceMatrix {
  const channelsByType = {} as Record<NotificationType, Record<NotificationChannel, boolean>>;

  for (const type of ALL_NOTIFICATION_TYPES) {
    const isEmergency = type === 'Emergency Alert';
    const isCritical =
      type === 'Schedule / Room Change' || type === 'Competition Update';

    channelsByType[type] = {
      'In-App': true,
      Email: isEmergency || isCritical || type === 'Ceremony',
      SMS:
        isEmergency ||
        (role === 'Volunteer' && type === 'Food & Logistics'),
      'Push Notification':
        isEmergency || isCritical || type === 'Food & Logistics',
      'Web Notification':
        isEmergency || isCritical || type === 'General',
    };
  }

  return {
    role,
    browserPushEnabled: true,
    quietHoursEnabled: role !== 'Organizer' && role !== 'Volunteer',
    quietHoursStart: '23:00',
    quietHoursEnd: '07:00',
    digestFrequency: 'Instant',
    channelsByType,
  };
}

